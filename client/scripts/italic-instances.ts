/**
 * Hubot Sans italic appears only in wide black capitals (`type-wide font-black italic`: the
 * wordmark, page titles, position chips), so the app ships that one instance of the italic
 * instead of the whole variable font: about 21 kB for Latin instead of 101 kB, the largest saving
 * on the first load. Run after a @fontsource-variable/hubot-sans upgrade (needs fonttools,
 * `pip install fonttools brotli`):
 *
 *   npm run italic-instances -w client
 *
 * Writes client/src/fonts/*.woff2 and client/src/fonts/hubot-sans-italic.css.
 */
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_DIR = fileURLToPath(
	new URL('../../node_modules/@fontsource-variable/hubot-sans/', import.meta.url)
);

const FONTS_DIR = fileURLToPath(new URL('../src/fonts/', import.meta.url));

/** The one italic the identity uses: `font-black` and `type-wide`. */
const AXES = { wght: 900, wdth: 125 } as const;

type Face = { file: string; unicodeRange: string };

/** The subsets and their ranges, as Fontsource declares them for the variable italic. */
function italicFaces(css: string): Face[] {
	return [
		...css.matchAll(
			/url\(\.\/files\/([\w-]+-standard-italic)\.woff2\)[^;]*;\s*unicode-range: ([^;]+);/g
		)
	].map((match) => ({ file: match[1] ?? '', unicodeRange: match[2] ?? '' }));
}

function fontFace(face: Face): string {
	return [
		'@font-face {',
		`\tfont-family: 'Hubot Sans Variable';`,
		'\tfont-style: italic;',
		'\tfont-display: swap;',
		`\tfont-weight: ${AXES.wght};`,
		`\tfont-stretch: ${AXES.wdth}%;`,
		`\tsrc: url(./${face.file}-${AXES.wght}.woff2) format('woff2');`,
		`\tunicode-range: ${face.unicodeRange};`,
		'}'
	].join('\n');
}

const faces = italicFaces(await readFile(`${SOURCE_DIR}standard-italic.css`, 'utf8'));

if (faces.length === 0) {
	throw new Error('No italic faces found in the Fontsource stylesheet; its format changed');
}

await mkdir(FONTS_DIR, { recursive: true });

for (const face of faces) {
	const made = spawnSync(
		'fonttools',
		[
			'varLib.instancer',
			`${SOURCE_DIR}files/${face.file}.woff2`,
			`wght=${AXES.wght}`,
			`wdth=${AXES.wdth}`,
			'-o',
			`${FONTS_DIR}${face.file}-${AXES.wght}.woff2`
		],
		{ stdio: 'inherit' }
	);

	if (made.status !== 0) {
		throw new Error(`fonttools could not instance ${face.file}; is fonttools installed?`);
	}
}

const stylesheet = `${FONTS_DIR}hubot-sans-italic.css`;

await writeFile(
	stylesheet,
	`/* Generated by scripts/italic-instances.ts: Hubot Sans italic at weight ${AXES.wght}, width ${AXES.wdth}%. */\n\n${faces.map(fontFace).join('\n\n')}\n`
);

spawnSync('npx', ['prettier', '--write', stylesheet], { stdio: 'inherit' });
